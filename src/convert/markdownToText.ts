// @/lib/convert/markdownToText.ts


export const markdownToText = (markdown: string): string => {
  if (!markdown) return '';
  return markdown
    .replace(/\r\n/g, '\n')
    .replace(/```[\s\S]*?```/g, '') // 去除代码块语法
    .replace(/\{\{\{([^}]*)\}\}\}/g, '$1') // 保留 {{{ }}} 内的内容，去除语法
    .replace(/!\[(.*?)\]\(.*?\)/g, '$1') // 保留图片描述，移除![]()语法
    .replace(/｛｛｛([^｝]*)｝｝｝/g, '$1') // 保留全角 ｛｛｛｝｝｝ 内的内容，去除语法
    .replace(/\{\{([^}]+)\}\}/g, '$1') // 保留双大括号内的内容，去除语法
    .replace(/｛｛([^｝]+)｝｝/g, '$1') // 保留全角双大括号内的内容，去除语法
    .replace(/【【([^】]*)】】/g, '$1') // 保留 【【】】 内的内容，去除语法
    .replace(/==([^=]+)==/g, '$1') // 去除高亮语法
    .replace(/\^\^([^\^]+)\^\^/g, '$1') // 去除上标语法
    .replace(/\[\[([^\]]+)\]\]/g, '$1') // 去除双中括号语法
    .replace(/^#+\s*/gm, '') // 去除标题语法
    .replace(/(\*\*|__)(.*?)\1/g, '$2') // 去除加粗语法
    .replace(/(\*|_)(.*?)\1/g, '$2') // 去除斜体语法
    .replace(/^[-*+]\s+/gm, '') // 去除无序列表语法
    .replace(/^\d+\.\s+/gm, '') // 去除有序列表语法
    .replace(/`([^`]+)`/g, '$1') // 去除行内代码语法
    .replace(/\[([^\]]+)\]\([^\)]+\)/g, '$1') // 去除链接语法
    .replace(/^>\s*/gm, '') // 去除引用语法
    .replace(/^(?:[-*_]){3,}\s*$/gm, '') // 去除分隔线语法
    .replace(/^[\|\s:-]+$/gm, '') // 去除表格分隔行
    .replace(/^\||\|$/gm, '') // 去除表格行首尾的竖线
    .replace(/\|/g, ' ') // 将表格中的竖线替换为空格
    .replace(/\\([[\](){}#*+\-_.!`])/g, '$1') // 去除转义字符
    .replace(/[ \t]+/g, ' ') // 将连续的空格和制表符替换为单个空格
    .replace(/\n{2,}/g, '\n') // 将连续的换行符替换为单个换行符
    .trim();
};
